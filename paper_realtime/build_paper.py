def column_rect(col, floats_here):
    x0, x1 = (ts.LX0, ts.LX1) if col == "L" else (ts.RX0, ts.RX1)
    y0, y1 = ts.TOP, ts.BOT
    for name, where in floats_here:
        h = FL[name][1]
        if where in (f"{col}-top", "F-top"):
            y0 = max(y0, ts.TOP + h + 12)
        if where in (f"{col}-bot", "F-bot"):
            y1 = min(y1, ts.BOT - h - 12)
    return pymupdf.Rect(x0, y0, x1, y1)


def float_rects(floats_here):
    out = []
    ftop = sum(FL[n][1] + 12 for n, w in floats_here if w == "F-top")
    fbot = sum(FL[n][1] + 12 for n, w in floats_here if w == "F-bot")
    stack = {"L-top": ts.TOP + ftop, "R-top": ts.TOP + ftop, "F-top": ts.TOP,
             "L-bot": ts.BOT - fbot, "R-bot": ts.BOT - fbot, "F-bot": ts.BOT}
    for name, where in floats_here:
        doc, h = FL[name]
        wdt = doc[0].rect.width
        x0 = ts.LX0 + (ts.FULLW - wdt) / 2 if where.startswith("F") else \
            (ts.LX0 if where[0] == "L" else ts.RX0) + (ts.COLW - wdt) / 2
        if where.endswith("top"):
            y0 = stack[where]
            stack[where] += h + 12
        else:
            y0 = stack[where] - h
            stack[where] -= h + 12
        out.append((name, pymupdf.Rect(x0, y0, x0 + wdt, y0 + h)))
    return out


