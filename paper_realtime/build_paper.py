def sci(v, nd=1):
    m, e = f"{v:.{nd}e}".split("e")
    e = int(e)
    if float(m) == 1.0 and nd <= 1:
        return f"10<sup>{'&#x2212;' if e < 0 else ''}{abs(e)}</sup>"
    return f"{m}&#x202f;&#xd7;&#x202f;10<sup>{'&#x2212;' if e < 0 else ''}{abs(e)}</sup>"


def sci_u(v, nd=1):
    """Plain-text scientific notation with Unicode superscripts (for tables)."""
