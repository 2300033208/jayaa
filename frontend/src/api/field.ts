import type { Dataset, FieldResults, TerrainCrs, TerrainModel, TerrainModelDetail, TerrainPreview } from '../types/field'
import { apiUrl, noContent, request } from './client'
import {
  parseDataset,
  parseDatasetList,
  parseFieldResults,
  parseTerrainList,
  parseTerrainModel,
  parseTerrainModelDetail,
  parseTerrainPreview,
} from './fieldSchemas'

const enc = encodeURIComponent
const UPLOAD = { timeoutMs: 180_000, retries: 0 }

/* ------------------------------------------------------------------ field datasets */

export interface DatasetUpload {
  name: string
  file: File
  referenceX: number | null
  referenceY: number | null
  referenceHeight: number | null
}

export function listDatasets(experimentId: string, signal?: AbortSignal): Promise<Dataset[]> {
  return request(`/api/experiments/${enc(experimentId)}/datasets`, parseDatasetList, { signal })
}

export function uploadDataset(experimentId: string, upload: DatasetUpload): Promise<Dataset> {
  const form = new FormData()
  form.set('name', upload.name)
  form.set('file', upload.file, upload.file.name)
  if (upload.referenceX !== null) form.set('reference_x_m', String(upload.referenceX))
  if (upload.referenceY !== null) form.set('reference_y_m', String(upload.referenceY))
  if (upload.referenceHeight !== null) form.set('reference_height_m', String(upload.referenceHeight))
  return request(`/api/experiments/${enc(experimentId)}/datasets`, parseDataset, { method: 'POST', form, ...UPLOAD })
}

export function getDataset(id: string, signal?: AbortSignal): Promise<Dataset> {
  return request(`/api/datasets/${enc(id)}`, parseDataset, { signal })
}

export function getDatasetResults(id: string, signal?: AbortSignal): Promise<FieldResults> {
  return request(`/api/datasets/${enc(id)}/results`, parseFieldResults, { signal, timeoutMs: 60_000 })
}

export function reanalyseDataset(id: string): Promise<Dataset> {
  return request(`/api/datasets/${enc(id)}/analyse`, parseDataset, { method: 'POST' })
}

export function cancelDataset(id: string): Promise<Dataset> {
  return request(`/api/datasets/${enc(id)}/cancel`, parseDataset, { method: 'POST' })
}

export function deleteDataset(id: string): Promise<null> {
  return request(`/api/datasets/${enc(id)}`, noContent, { method: 'DELETE' })
}

/** CSV with the planned stations and times, generated by the engine from the experiment. */
export function datasetTemplateUrl(experimentId: string): string {
  return apiUrl(`/api/experiments/${enc(experimentId)}/datasets/template`)
}

/* ------------------------------------------------------------------ elevation models */

export interface TerrainUpload {
  name: string
  file: File
  /** null: taken from the GeoTIFF (required for ASCII grids). */
  crs: TerrainCrs | null
  utmZone: number | null
  hemisphere: 'north' | 'south' | null
}

export function listTerrainModels(signal?: AbortSignal): Promise<TerrainModel[]> {
  return request('/api/terrain-models', parseTerrainList, { signal })
}

export function uploadTerrainModel(upload: TerrainUpload): Promise<TerrainModel> {
  const form = new FormData()
  form.set('name', upload.name)
  form.set('file', upload.file, upload.file.name)
  if (upload.crs !== null) form.set('crs', upload.crs)
  if (upload.utmZone !== null) form.set('utm_zone', String(upload.utmZone))
  if (upload.hemisphere !== null) form.set('hemisphere', upload.hemisphere)
  return request('/api/terrain-models', parseTerrainModel, { method: 'POST', form, ...UPLOAD })
}

export function getTerrainModel(id: string, signal?: AbortSignal): Promise<TerrainModelDetail> {
  return request(`/api/terrain-models/${enc(id)}`, parseTerrainModelDetail, { signal })
}

export function getTerrainPreview(id: string, signal?: AbortSignal): Promise<TerrainPreview> {
  return request(`/api/terrain-models/${enc(id)}/preview`, parseTerrainPreview, { signal, timeoutMs: 30_000 })
}

export function deleteTerrainModel(id: string): Promise<null> {
  return request(`/api/terrain-models/${enc(id)}`, noContent, { method: 'DELETE' })
}
